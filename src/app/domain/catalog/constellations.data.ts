import { STARS } from './stars.data';

function edges(...pairs: [string, string][]): ConstellationEdge[] {
  return pairs.map(([fromStarId, toStarId]) => ({ fromStarId, toStarId }));
}

function starIdsFor(constellationId: string): string[] {
  return STARS.filter((s) => s.constellationId === constellationId).map((s) => s.id);
}

